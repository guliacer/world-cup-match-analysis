def build_score_model(home_lam=2.05, away_lam=0.55):
    scores = []
    totals = {i: 0.0 for i in range(8)}
    home = draw = away = 0.0
    half = {(h, a): 0.0 for h in ["胜", "平", "负"] for a in ["胜", "平", "负"]}

    for i in range(10):
        pi = poisson(home_lam, i)
        for j in range(10):
            pj = poisson(away_lam, j)
            prob = pi * pj
            if i > j:
                home += prob
                full = "胜"
            elif i == j:
                draw += prob
                full = "平"
            else:
                away += prob
                full = "负"

            if i <= 7 and j <= 7:
                scores.append((prob, f"{i}-{j}"))
                total = i + j
                totals[7 if total >= 7 else total] += prob

    # Independent half-time approximation with lower expected goals.
    half_home_lam = 0.78
    half_away_lam = 0.22
    for hi in range(6):
        hpi = poisson(half_home_lam, hi)
        for hj in range(6):
            hpj = poisson(half_away_lam, hj)
            hprob = hpi * hpj
            if hi > hj:
                half_result = "胜"
            elif hi == hj:
                half_result = "平"
            else:
                half_result = "负"

            for fi in range(8):
                fpi = poisson(home_lam, fi)
                for fj in range(8):
                    fpj = poisson(away_lam, fj)
                    fprob = fpi * fpj
                    if fi > fj:
                        full_result = "胜"
                    elif fi == fj:
                        full_result = "平"
                    else:
                        full_result = "负"
                    half[(half_result, full_result)] += hprob * fprob

    scores.sort(key=lambda item: item[0], reverse=True)
    return {
        "home_lam": home_lam,
        "away_lam": away_lam,
        "home": home,
        "draw": draw,
        "away": away,
        "scores": scores[:6],
        "totals": totals,
        "half": half,
    }


def unique_path(path: Path) -> Path:
    if not path.exists():
        return path
    stem = path.stem
    suffix = path.suffix
    index = 2
    while True:
        candidate = path.with_name(f"{stem}_{index}{suffix}")
        if not candidate.exists():
            return candidate
        index += 1


