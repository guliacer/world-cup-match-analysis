def poisson(lam: float, goals: int) -> float:
    return math.exp(-lam) * (lam**goals) / math.factorial(goals)


def pct(value: float, digits: int = 1) -> str:
    return f"{value:.{digits}f}%"


def esc(value) -> str:
    return html.escape(str(value), quote=False)


def unique_path(path: Path) -> Path:
    if not path.exists():
        return path
    index = 2
    while True:
        candidate = path.with_name(f"{path.stem}_{index}{path.suffix}")
        if not candidate.exists():
            return candidate
        index += 1


def build_score_model(home_lam=1.82, away_lam=0.78):
    scores = []
    totals = {i: 0.0 for i in range(8)}
    home = draw = away = 0.0

    for i in range(13):
        pi = poisson(home_lam, i)
        for j in range(13):
            prob = pi * poisson(away_lam, j)
            if i > j:
                home += prob
            elif i == j:
                draw += prob
            else:
                away += prob

            scores.append((prob, f"{i}:{j}"))
            totals[7 if i + j >= 7 else i + j] += prob

    half_home_lam = home_lam * 0.42
    half_away_lam = away_lam * 0.42
    half_probs = {"胜": 0.0, "平": 0.0, "负": 0.0}
    for i in range(8):
        for j in range(8):
            prob = poisson(half_home_lam, i) * poisson(half_away_lam, j)
            if i > j:
                half_probs["胜"] += prob
            elif i == j:
                half_probs["平"] += prob
            else:
                half_probs["负"] += prob

    full_probs = {"胜": home, "平": draw, "负": away}
    half_full = {(h, f): half_probs[h] * full_probs[f] for h in half_probs for f in full_probs}

    scores.sort(key=lambda item: item[0], reverse=True)
    return {
        "home_lam": home_lam,
        "away_lam": away_lam,
        "home": home,
        "draw": draw,
        "away": away,
        "scores": scores[:6],
        "totals": totals,
        "half": half_probs,
        "half_full": half_full,
    }


def remove_between(text: str, start_marker: str, end_marker: str) -> str:
    pattern = re.escape(start_marker) + r".*?" + re.escape(end_marker)
    return re.sub(pattern, end_marker, text, flags=re.S)


def remove_rows_containing(text: str, labels) -> str:
    for label in labels:
        text = re.sub(
            r"\s*<tr\b[^>]*>(?:(?!</tr>).)*" + re.escape(label) + r"(?:(?!</tr>).)*</tr>",
            "",
            text,
            flags=re.S,
        )
    return text


def clean_segment_rows(text: str, start_marker: str, end_marker: str, labels) -> str:
    start = text.find(start_marker)
    end = text.find(end_marker)
    if start == -1 or end == -1 or end <= start:
        return text
    segment = remove_rows_containing(text[start:end], labels)
    return text[:start] + segment + text[end:]


